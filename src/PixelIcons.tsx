function make(key: keyof typeof drawings) {
  const rows = drawings[key],
    height = rows.length;
  const d = rows
    .flatMap((row, y) => {
      const runs = [];
      for (let x = 0; x < 16; x++) {
        if (row[x] !== "#") continue;
        const start = x;
        while (x + 1 < 16 && row[x + 1] === "#") x++;
        runs.push(
          `M${start} ${y + (16 - height) / 2}h${x - start + 1}v1H${start}z`,
        );
      }
      return runs;
    })
    .join("");
  return function Icon({
    size = 24,
    strokeWidth: _stroke,
    className = "",
    ...props
  }: Props) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 16 16"
        fill="currentColor"
        className={"pixel-icon " + className}
        shapeRendering="crispEdges"
        aria-hidden="true"
        {...props}
      >
        <path d={d} />
      </svg>
    );
  };
}
